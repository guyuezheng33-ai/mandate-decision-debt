'use strict';

/**
 * 把"我确实跑过"变成一份可提交的证据。
 *
 * judges 不会 clone 仓库跑 104 条断言，但他们会看一张"每条断言在守什么"的表。
 * 手写这张表会立刻过期，所以它由脚本从 TAP 输出生成：
 *
 *   npm run proof   → docs/verification.md
 */

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const TEST_DIR = path.join(__dirname, 'test');
const OUT = path.join(__dirname, 'docs', 'verification.md');

const WHY = {
  'rules.test.js': '六条判据在什么数据上命中、什么情况下必须沉默',
  'tri.test.js': '三值证据：present / absent / unknown 的边界',
  'profiles.test.js': '三套口径的权重与英雄判据互不相同',
  'score.test.js': '分数、grade 与"全不可知时不出分"',
  'compact.test.js': 'payload 白名单与 200KB 上限',
  'ports.test.js': '四个端口实现共用同一份契约',
  'chain.test.js': 'TWG→REST 降级：只在整体不可用时降，且把盲区压成 unknown',
  'entry.test.js': 'Forge handler 形状与错误码透传',
  'agent-entry.test.js': 'Rovo action / MCP 的入参形状、补水、图的映射',
  'copy.test.js': '每个错误码在中英文都有文案，英文里不许混中文',
  'hardening.test.js': '超时、重试、缓存跨用户隔离、扫描只一次往返',
  'write.test.js': '留痕闭环：ADF 往返、指纹幂等、写完读回、写后分数真的下降',
  'cache.test.js': '并发单飞只打一次；失效之后回来的旧结果不许写回',
  'robustness.test.js': '200 轮畸形数据不崩；三个时区同一个分数',
  'golden.test.js': '五条 fixture × 三口径的分数钉死（谁调权重，这里先红）',
};

const files = fs
  .readdirSync(TEST_DIR)
  .filter((f) => f.endsWith('.test.js'))
  .sort();

const rows = [];
let total = 0;
let failed = 0;

for (const file of files) {
  const res = spawnSync(process.execPath, ['--test', '--test-reporter=tap', path.join(TEST_DIR, file)], { encoding: 'utf8' });
  const lines = (res.stdout || '').split(/\r?\n/);
  for (const line of lines) {
    const m = line.match(/^(ok|not ok)\s+\d+\s+-\s+(.+)$/);
    if (!m) continue;
    total += 1;
    if (m[1] === 'not ok') failed += 1;
    rows.push({ file, name: m[2].trim(), ok: m[1] === 'ok' });
  }
}

const bench = spawnSync(process.execPath, [path.join(__dirname, 'bench.js')], { encoding: 'utf8' });
const benchLine = bench.status === 0
  ? 'bench 500 items × 3 lenses · 1500 scores · p50 within 300ms budget (live number: npm run bench)'
  : 'bench FAILED';
const mk = spawnSync(process.execPath, [path.join(__dirname, 'marketplace', 'check.js')], { encoding: 'utf8' });
const mkLine = (mk.stdout || '').trim().split(/\r?\n/).pop() || '';

const date = new Date().toLocaleDateString('sv-SE');
const md = [
  '# Verification record',
  '',
  `Generated by \`npm run proof\` on ${date}. Every row below is a real assertion run against this tree,`,
  'not a claim. Re-run it yourself: `npm run ci` prints one line, `npm run proof` regenerates this file.',
  '',
  `**${total} assertions · ${failed === 0 ? 'all passing' : `${failed} failing`}**`,
  '',
  '| File | Assertion | Status |',
  '|---|---|---|',
  ...rows.map((r) => `| \`${r.file}\` | ${r.name.replace(/\|/g, '\\|')} | ${r.ok ? 'pass' : 'FAIL'} |`),
  '',
  '## Why each file exists',
  '',
  '| File | What it protects |',
  '|---|---|',
  ...files.map((f) => `| \`${f}\` | ${WHY[f] || '—'} |`),
  '',
  '## Scale and packaging',
  '',
  '```',
  benchLine,
  mkLine,
  '```',
  '',
  'The marketplace check is the one place where a red row is expected before release: `app.id`, the icon URL,',
  'the support email and the privacy URL are filled in after `forge register`, which needs a site and a login.',
  '',
].join('\n');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md, 'utf8');
process.stdout.write(`written: ${path.relative(__dirname, OUT)}  (${total} assertions, ${failed} failing)\n`);
process.exit(failed === 0 ? 0 : 1);
